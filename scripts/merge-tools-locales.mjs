/**
 * Merge per-locale tool translation JSON fragments into messages overlays.
 * Fragments live in: lib/i18n/tools-locales/<locale>/*.json
 * Output: lib/i18n/tools-locales/index.ts
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.join(process.cwd(), 'lib', 'i18n', 'tools-locales')
const LOCALES = ['fr', 'es', 'ja', 'nl', 'sv', 'it', 'ru', 'id', 'ko', 'tr', 'ar']

function deepMerge(a, b) {
  const out = { ...a }
  for (const [k, v] of Object.entries(b)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && out[k] && typeof out[k] === 'object') {
      out[k] = deepMerge(out[k], v)
    } else {
      out[k] = v
    }
  }
  return out
}

const byLocale = Object.fromEntries(LOCALES.map((l) => [l, {}]))
let files = 0

for (const locale of LOCALES) {
  const dir = path.join(ROOT, locale)
  if (!fs.existsSync(dir)) continue
  const allPath = path.join(dir, 'all.json')
  // Prefer complete all.json when present (avoids corrupt/partial batch fragments).
  if (fs.existsSync(allPath)) {
    byLocale[locale] = JSON.parse(fs.readFileSync(allPath, 'utf8'))
    files++
    continue
  }
  for (const name of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const data = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'))
    byLocale[locale] = deepMerge(byLocale[locale], data)
    files++
  }
}

// coverage vs English
const en = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'tmp-en-tools.json'), 'utf8'))
const enKeys = Object.keys(en)
const report = {}
for (const locale of LOCALES) {
  const have = Object.keys(byLocale[locale] || {})
  report[locale] = {
    tools: have.length,
    missing: enKeys.filter((k) => !have.includes(k)),
  }
}

fs.writeFileSync(path.join(ROOT, 'coverage.json'), JSON.stringify(report, null, 2))

const lines = [
  '/** Auto-generated by scripts/merge-tools-locales.mjs — do not edit by hand. */',
  'export const toolsLocales = ' + JSON.stringify(byLocale, null, 2) + ' as const',
  '',
]
fs.writeFileSync(path.join(ROOT, 'index.ts'), lines.join('\n'))
console.log(JSON.stringify({ files, report: Object.fromEntries(Object.entries(report).map(([k, v]) => [k, { tools: v.tools, missing: v.missing.length }])) }, null, 2))
