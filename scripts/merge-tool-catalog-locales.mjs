/**
 * Merge lib/i18n/tool-catalog-locales/<locale>/*.json → index.ts
 * Prefer all.json when present.
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.join(process.cwd(), 'lib', 'i18n', 'tool-catalog-locales')
const LOCALES = ['de', 'fr', 'es', 'ja', 'nl', 'sv', 'it', 'ru', 'id', 'ko', 'tr', 'ar']
const en = JSON.parse(fs.readFileSync('tmp-en-tool-catalog.json', 'utf8'))
const enKeys = Object.keys(en)

function deepMerge(a, b) {
  return { ...a, ...b }
}

const byLocale = Object.fromEntries(LOCALES.map((l) => [l, {}]))
let files = 0

for (const locale of LOCALES) {
  const dir = path.join(ROOT, locale)
  fs.mkdirSync(dir, { recursive: true })
  if (!fs.existsSync(dir)) continue
  const allPath = path.join(dir, 'all.json')
  if (fs.existsSync(allPath)) {
    byLocale[locale] = JSON.parse(fs.readFileSync(allPath, 'utf8'))
    files++
    continue
  }
  for (const name of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    byLocale[locale] = deepMerge(
      byLocale[locale],
      JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8')),
    )
    files++
  }
}

const report = {}
for (const locale of LOCALES) {
  const have = Object.keys(byLocale[locale] || {})
  report[locale] = {
    tools: have.length,
    missing: enKeys.filter((k) => !have.includes(k)),
  }
}
fs.writeFileSync(path.join(ROOT, 'coverage.json'), JSON.stringify(report, null, 2))

const body =
  '/** Auto-generated by scripts/merge-tool-catalog-locales.mjs — do not edit by hand. */\n' +
  'export const toolCatalogLocales = ' +
  JSON.stringify(byLocale, null, 2) +
  ' as const\n'

fs.writeFileSync(path.join(ROOT, 'index.ts'), body)
console.log(
  JSON.stringify(
    {
      files,
      report: Object.fromEntries(
        Object.entries(report).map(([k, v]) => [k, { tools: v.tools, missing: v.missing.length }]),
      ),
    },
    null,
    2,
  ),
)
